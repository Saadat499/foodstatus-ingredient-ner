"""
Evaluate the photo path (quality gate -> OCR -> OCR cleanup) on real photos.

Every other number in this repository starts from typed or API text. This
script measures the part that does not: what happens to a photograph of an
ingredient label.

INPUT
    A folder of photos and a CSV of ground truth that YOU type from the
    label (never generated by this system). Columns:

        photo_file             file name inside --photos_dir
        source                 own_package | printed_off | off_image
                               (kept separate in the report on purpose: a
                               printed or on-screen label is not a real
                               shelf photo)
        product_or_barcode     free text, for your own reference
        true_ingredient_text   the ingredient list exactly as printed
        lighting, angle, notes optional free text

    Start from results/photo_metadata_TEMPLATE.csv.

WHAT IT MEASURES (per photo, then per source)
    gate_pass          did the blur / text-height check accept the photo
    cer                character error rate of the cleaned OCR text against
                       the true text (lower is better; 0 = identical).
                       Letters and digits only, case-insensitive.
    recall_exact       share of true ingredients that appear, after
                       normalisation, as an exact entry in the cleaned text
    recall_near        same, but allowing a close spelling (similarity >= 0.85)

    OCR metrics are computed on photos that pass the gate, because those are
    the ones the app would actually read. Use --ocr_rejected to also score
    the rejected ones (useful to check whether the gate is too strict).

OUTPUT
    results/photo_eval_results.csv   one row per photo
    results/photo_eval_summary.csv   one row per source plus an "all" row

It does not run the classifier, so it needs no model, only Tesseract.

Usage (from the repository root):
    python tools/eval_photos.py --photos_dir photos --metadata results/photo_metadata.csv
"""

import argparse
import csv
import difflib
import os
import re
import statistics
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))

NEAR_THRESHOLD = 0.85


# ---------------------------------------------------------------- metrics

def normalise(text: str) -> str:
    """Lowercase; keep letters and digits only (spaces collapsed)."""
    text = re.sub(r"[^a-z0-9 ]+", " ", (text or "").lower())
    return re.sub(r"\s+", " ", text).strip()


def edit_distance(a: str, b: str) -> int:
    if not a:
        return len(b)
    if not b:
        return len(a)
    prev = list(range(len(b) + 1))
    for i, ca in enumerate(a, 1):
        cur = [i]
        for j, cb in enumerate(b, 1):
            cur.append(min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + (ca != cb)))
        prev = cur
    return prev[-1]


def cer(predicted: str, truth: str):
    """Character error rate against the truth; None if the truth is empty."""
    t = normalise(truth)
    if not t:
        return None
    return edit_distance(normalise(predicted), t) / len(t)


def split_ingredients(text: str) -> list:
    """Split on commas/semicolons outside brackets; normalise each piece."""
    parts, depth, cur = [], 0, []
    for ch in text or "":
        if ch in "([{":
            depth += 1
        elif ch in ")]}":
            depth = max(0, depth - 1)
        if ch in ",;" and depth == 0:
            parts.append("".join(cur))
            cur = []
        else:
            cur.append(ch)
    parts.append("".join(cur))
    out = []
    for p in parts:
        # compare on the name only, so "gelatin (bovine)" ~ "gelatin"
        name = normalise(re.sub(r"[\(\[\{].*", "", p))
        if name:
            out.append(name)
    return out


def ingredient_recall(predicted_text: str, truth_text: str):
    """Returns (exact, near) recall, or (None, None) if truth is empty."""
    truth = split_ingredients(truth_text)
    if not truth:
        return None, None
    pred = split_ingredients(predicted_text)
    pred_set = set(pred)
    exact = sum(1 for t in truth if t in pred_set)
    near = sum(
        1 for t in truth
        if t in pred_set or any(
            difflib.SequenceMatcher(None, t, p).ratio() >= NEAR_THRESHOLD
            for p in pred)
    )
    return exact / len(truth), near / len(truth)


# -------------------------------------------------------------------- OCR

def run_ocr(image):
    """Same orientation handling as src/app.py run_ocr (kept in sync by hand,
    because importing app.py would start the Streamlit UI)."""
    import pytesseract
    candidates = [image]
    try:
        osd = pytesseract.image_to_osd(image, output_type=pytesseract.Output.DICT)
        rotation = osd.get("rotate", 0)
        if rotation:
            candidates.append(image.rotate(-rotation, expand=True))
    except Exception:
        pass
    best_text, best_conf = "", -1.0
    for cand in candidates:
        data = pytesseract.image_to_data(cand, output_type=pytesseract.Output.DICT)
        confs = [int(c) for c in data["conf"] if str(c) not in ("-1",)]
        avg = sum(confs) / len(confs) if confs else -1.0
        if avg > best_conf:
            best_conf = avg
            best_text = pytesseract.image_to_string(cand)
    return best_text


def evaluate_photo(row, photos_dir, ocr_rejected):
    from PIL import Image
    from photo_quality import assess_photo_quality
    from ocr_bridge import clean_ocr_text

    out = {k: row.get(k, "") for k in
           ("photo_file", "source", "product_or_barcode", "lighting", "angle")}
    path = os.path.join(photos_dir, row["photo_file"])
    if not os.path.exists(path):
        out.update(status="missing_file")
        return out
    image = Image.open(path).convert("RGB")
    q = assess_photo_quality(image)
    gate_pass = not (q["is_too_blurry"] or q["is_text_too_small"])
    out.update(
        status="ok",
        gate_pass=int(gate_pass),
        blur_score=round(q["blur_score"], 1),
        text_height_px=round(q["text_height_px"], 1),
        reject_reason=("" if gate_pass else
                       "text_too_small" if q["is_text_too_small"] else "too_blurry"),
    )
    if not gate_pass and not ocr_rejected:
        return out
    cleaned = clean_ocr_text(run_ocr(image))["cleaned_text"]
    truth = row.get("true_ingredient_text", "")
    c = cer(cleaned, truth)
    r_exact, r_near = ingredient_recall(cleaned, truth)
    out.update(
        cer=None if c is None else round(c, 4),
        recall_exact=None if r_exact is None else round(r_exact, 4),
        recall_near=None if r_near is None else round(r_near, 4),
        cleaned_text=cleaned,
    )
    return out


# ---------------------------------------------------------------- summary

def _mean(values):
    vals = [v for v in values if isinstance(v, (int, float))]
    return round(statistics.mean(vals), 4) if vals else ""


def summarise(rows):
    groups = {}
    for r in rows:
        if r.get("status") != "ok":
            continue
        groups.setdefault(r["source"], []).append(r)
        groups.setdefault("all", []).append(r)
    summary = []
    for name in sorted(groups, key=lambda s: (s == "all", s)):
        g = groups[name]
        passed = sum(r["gate_pass"] for r in g)
        scored = [r for r in g if "cer" in r]
        summary.append({
            "source": name,
            "photos": len(g),
            "gate_pass": passed,
            "gate_pass_rate": round(passed / len(g), 4),
            "photos_scored": len(scored),
            "mean_cer": _mean([r["cer"] for r in scored]),
            "mean_recall_exact": _mean([r["recall_exact"] for r in scored]),
            "mean_recall_near": _mean([r["recall_near"] for r in scored]),
        })
    return summary


def write_csv(path, rows, fields):
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=fields, extrasaction="ignore")
        w.writeheader()
        w.writerows(rows)


def main():
    p = argparse.ArgumentParser(description=__doc__.split("\n")[1])
    p.add_argument("--photos_dir", default="photos")
    p.add_argument("--metadata", default="results/photo_metadata.csv")
    p.add_argument("--out_dir", default="results")
    p.add_argument("--ocr_rejected", action="store_true",
                   help="Also OCR and score photos the quality gate rejected.")
    args = p.parse_args()

    with open(args.metadata, newline="", encoding="utf-8") as f:
        meta = list(csv.DictReader(f))
    if not meta:
        sys.exit(f"{args.metadata} has no rows. Add photos first "
                 "(see results/photo_metadata_TEMPLATE.csv).")

    rows = [evaluate_photo(r, args.photos_dir, args.ocr_rejected) for r in meta]
    summary = summarise(rows)

    write_csv(os.path.join(args.out_dir, "photo_eval_results.csv"), rows,
              ["photo_file", "source", "product_or_barcode", "lighting", "angle",
               "status", "gate_pass", "reject_reason", "blur_score",
               "text_height_px", "cer", "recall_exact", "recall_near",
               "cleaned_text"])
    write_csv(os.path.join(args.out_dir, "photo_eval_summary.csv"), summary,
              ["source", "photos", "gate_pass", "gate_pass_rate", "photos_scored",
               "mean_cer", "mean_recall_exact", "mean_recall_near"])

    missing = [r["photo_file"] for r in rows if r.get("status") == "missing_file"]
    for s in summary:
        print(s)
    if missing:
        print(f"WARNING: {len(missing)} file(s) not found in {args.photos_dir}: "
              + ", ".join(missing))


if __name__ == "__main__":
    main()
